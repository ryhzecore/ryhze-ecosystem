#!/usr/bin/env python3
"""Create a deterministic, exact NSIS file list for a verified Windows bundle.

This does not compile, sign, execute, install, or publish an application.
"""
from __future__ import annotations

import argparse
from pathlib import Path, PureWindowsPath
import re
import stat
import struct


_RESERVED = re.compile(r"^(CON|PRN|AUX|NUL|CLOCK\$|CONIN\$|CONOUT\$|COM[0-9¹²³]|LPT[0-9¹²³]) *(?:\..*)?$", re.I)


def _safe_component(value: str) -> bool:
    return bool(value) and not (
        value in (".", "..")
        or any(char in value for char in '\\/:*?"<>|$')
        or any(ord(char) < 32 or 127 <= ord(char) <= 159 for char in value)
        or value[-1] in " ."
        or _RESERVED.fullmatch(value)
    )


def bundle_files(bundle: Path) -> list[Path]:
    root_flags = getattr(bundle.lstat(), "st_file_attributes", 0) if bundle.exists() else 0
    if (not bundle.is_dir() or bundle.is_symlink()
            or root_flags & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 1024)):
        raise ValueError("BUNDLE_DIR must be a real directory")
    if not (bundle / "ryhze.exe").is_file():
        raise ValueError("The bundle must include ryhze.exe")
    files: list[Path] = []
    seen: set[str] = set()
    for path in sorted(bundle.rglob("*"), key=lambda p: str(p).casefold()):
        flags = getattr(path.lstat(), "st_file_attributes", 0)
        if path.is_symlink() or flags & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 1024):
            raise ValueError(f"Links and junctions are not package content: {path}")
        relative = path.relative_to(bundle)
        if not all(_safe_component(part) for part in relative.parts):
            raise ValueError(f"Unsafe Windows/NSIS filename: {relative}")
        key = str(PureWindowsPath(relative)).casefold()
        if key in seen:
            raise ValueError(f"Case-insensitive path collision: {relative}")
        seen.add(key)
        if path.is_file():
            files.append(relative)
        elif not path.is_dir():
            raise ValueError(f"Unsupported bundle entry: {relative}")
    return files


def render_manifest(files: list[Path]) -> str:
    directories = {Path(".")}
    for relative in files:
        directories.update(relative.parents)
    ordered = sorted(directories, key=lambda p: (len(p.parts), str(p).casefold()))

    def destination(path: Path) -> str:
        suffix = "" if path == Path(".") else "\\" + str(PureWindowsPath(path))
        return "$INSTDIR\\app" + suffix

    lines = ["; Generated by prepare_bundle.py. Do not edit.", "!macro InstallPayload"]
    for directory in ordered:
        lines.append(f'  SetOutPath "{destination(directory)}"')
        for relative in files:
            if relative.parent == directory:
                source = str(PureWindowsPath(relative))
                lines.append(f'  File "/oname={relative.name}" "${{BUNDLE_DIR}}\\{source}"')
    lines += ["!macroend", "", "!macro ValidatePayloadDirectories"]
    for directory in ordered:
        lines.append(f'  !insertmacro AssertNoReparsePoint "{destination(directory)}"')
    # Validate every known leaf before removal as well as its directory chain.
    # Unknown entries are neither followed nor removed.
    for relative in files:
        lines.append(f'  !insertmacro AssertNoReparsePoint "{destination(relative)}"')
    lines += ["!macroend", "", "!macro RemovePayload"]
    for relative in files:
        target = destination(relative)
        lines += [f'  ${{If}} ${{FileExists}} "{target}"', "    ClearErrors",
                  f'    Delete "{target}"', "    ${If} ${Errors}",
                  "      StrCpy $RemovalFailed 1", "    ${EndIf}", "  ${EndIf}"]
    lines += ["  ; Never recurse: leave any additional files and nonempty folders intact."]
    for directory in reversed(ordered):
        lines.append(f'  RMDir "{destination(directory)}"')
    lines += ["!macroend", ""]
    return "\n".join(lines)


def wizard_bitmap() -> bytes:
    """Original geometric graphite/blue artwork; no legacy UI assets copied."""
    width, height = 164, 314
    stride = (width * 3 + 3) & ~3
    pixels = bytearray()
    for y in range(height - 1, -1, -1):
        row = bytearray()
        for x in range(width):
            # Match the website: primary #165BFA, accent #84B6FF, surface #111214.
            accent = y > 250 and 24 < x < 140 and (x + y) % 43 < 7
            rgb = ((22, 91, 250) if x < 5 else
                   (132, 182, 255) if accent else (17, 18, 20))
            row.extend(reversed(rgb))
        pixels.extend(row + bytes(stride - width * 3))
    size = 54 + len(pixels)
    return (b"BM" + struct.pack("<IHHI", size, 0, 0, 54)
            + struct.pack("<IiiHHIIiiII", 40, width, height, 1, 24, 0, len(pixels), 2835, 2835, 0, 0)
            + pixels)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bundle-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    bundle = args.bundle_dir.absolute()
    output = args.output_dir.absolute()
    if output == bundle or bundle in output.parents:
        parser.error("Generated packaging files must be outside BUNDLE_DIR")
    try:
        files = bundle_files(bundle)
    except ValueError as error:
        parser.error(str(error))
    output.mkdir(parents=True, exist_ok=True)
    (output / "bundle.nsh").write_text(render_manifest(files), encoding="utf-8")
    (output / "wizard.bmp").write_bytes(wizard_bitmap())
    print(f"Prepared {len(files)} exact file entries in {output / 'bundle.nsh'}")


if __name__ == "__main__":
    main()
